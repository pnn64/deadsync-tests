local probe=assert(loadfile(GAMESTATE:GetCurrentSong():GetSongDir()..'probe.lua'))()
return Def.ActorFrame{OnCommand=function(self)
    probe(self)
    local screen=SCREENMAN:GetTopScreen()
    local combo=screen:GetChild('PlayerP1'):GetChild('Combo')
    assert(tostring(combo):match('^ActorFrame %('))
    assert(combo:GetNumChildren()==3)
    local description=screen:GetChild('StepsDescriptionP1')
    assert(description:GetText()=='Native chart description')
    assert(description:GetText()==GAMESTATE:GetCurrentSteps(PLAYER_1):GetDescription())
    assert(description:GetTweenTimeLeft()==math.huge)
    description:diffusealpha(0.5)
    assert(description:GetTweenTimeLeft()==math.huge)
    MESSAGEMAN:Broadcast('DuplicateGroupsChecked')
    MESSAGEMAN:Broadcast('ComboClassChecked')
    MESSAGEMAN:Broadcast('StepsDescriptionChecked')
end,Def.Quad{Name='same'},Def.Quad{Name='same'}}
